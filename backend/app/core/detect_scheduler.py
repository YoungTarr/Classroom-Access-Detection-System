"""ตัวจัดคิวการตรวจจับที่กล้องทุกตัวใช้ร่วมกัน (เฟส 8)

============================================================================
ปัญหาที่ไฟล์นี้แก้
============================================================================

พอมีกล้องสองตัว แต่ละตัวมีลูปตรวจจับของตัวเองที่เดินด้วย DETECT_FPS เท่ากัน
ถ้าปล่อยให้ทั้งคู่ยิงงานเข้า AI พร้อมกันทุกรอบ จะเกิดสองอาการ:

1. **แย่ง CPU กันจนช้าลงทั้งคู่**
   Pi 5 มี 4 core และต้องแบ่งให้ PostgreSQL กับการถอดรหัสวิดีโอสองสตรีมด้วย
   งานตรวจจับสองชุดพร้อมกันไม่ได้เร็วขึ้นเป็นสองเท่า แต่ช้าลงทั้งสองฝั่ง
   (ตัวตรวจจับมีล็อกของตัวเองอยู่แล้ว สุดท้ายก็ต้องเข้าคิวกันอยู่ดี
   แค่เข้าคิวแบบเสีย thread รออยู่เฉย ๆ ซึ่งไม่ได้อะไรเพิ่ม)

2. **ไม่ยุติธรรมและคาดเดาไม่ได้**
   ใครยิงถึงก่อนได้ก่อน กล้องตัวหนึ่งอาจได้ตรวจถี่กว่าอีกตัวเป็นช่วง ๆ
   แล้วกรอบของกล้องที่เสียเปรียบจะกระตุกกว่าโดยไม่มีเหตุผลที่อธิบายได้

============================================================================
วิธีแก้: ประตูบานเดียว + คิวมาก่อนได้ก่อน + เพดานรวมทั้งระบบ
============================================================================

    ประตูบานเดียว (asyncio.Lock)
        ตรวจได้ทีละกล้องเท่านั้น ไม่ใช่พร้อมกันทุกตัว
        asyncio.Lock ปล่อยให้ผู้รอตามลำดับที่มาถึง (FIFO) ซึ่งพอมีสองกล้อง
        ยิงสลับกันเรื่อย ๆ ก็ได้ผลเป็นการ "วนคิวทีละกล้อง" โดยอัตโนมัติ
        ไม่ต้องเขียนตัวนับรอบเอง

    กล้องที่ไม่มีของทำ ไม่ต้องมาต่อคิว
        ลูปตรวจจับจะขอคิว **หลังจาก** เห็นว่ามีเฟรมใหม่จริงแล้วเท่านั้น
        กล้องที่ถูกถอดปลั๊กจึงไม่มาจองคิวไว้เฉย ๆ
        อีกตัวจะได้คิวทุกรอบเต็มที่ ไม่ถูกถ่วงเลย (ข้อ 3 ของงานเฟสนี้)

    เพดานรวมทั้งระบบ (token bucket ที่ DETECT_FPS_TOTAL)
        DETECT_FPS เป็นค่า "ต่อกล้อง" ส่วนเพดานรวมคุมไม่ให้ผลรวมของทุกกล้อง
        ทะลุงบ CPU ที่ตั้งไว้ กล้องที่มาขอเกินงบจะถูกให้รอ ไม่ใช่ถูกทิ้งงาน
        (ทิ้งแล้วจะเสียเฟรมฟรี ๆ ทั้งที่แค่รออีกนิดก็ได้ตรวจ)

หมายเหตุ: ทุกคนที่ผ่านประตูนี้ยัง "ตรวจจริง" ใน thread แยกเหมือนเดิม
ตัวจัดคิวไม่ได้ทำให้งานหนักย้ายมาอยู่บน event loop
"""

from __future__ import annotations

import asyncio
import logging
import time

logger = logging.getLogger(__name__)


class DetectScheduler:
    """ประตูเข้าสู่การตรวจจับ ใช้ร่วมกันทุกกล้อง

    ใช้เป็น async context manager:

        async with scheduler.slot(camera_id):
            await asyncio.to_thread(pipeline.process, frame)

    ออกจาก with แล้วประตูจะถูกปล่อยเสมอ แม้ข้างในจะโยน exception
    (ถ้าลืมปล่อย กล้องทุกตัวจะค้างถาวรพร้อมกัน ซึ่งเป็นบั๊กที่แพงที่สุดของไฟล์นี้)
    """

    def __init__(self, total_fps: int) -> None:
        # เพดานรวมของทั้งระบบ ไม่ใช่ต่อกล้อง
        self.total_fps = max(1, total_fps)

        # ประตูบานเดียว: ตรวจได้ทีละกล้อง
        self._gate = asyncio.Lock()

        # ---- token bucket ของเพดานรวม ----
        # เพดานถังเป็น 1 พอ ไม่ให้สะสม token ไว้แล้วปล่อยรัวสองกล้องพร้อมกัน
        # (ต่างจาก token bucket ในที่อื่นของโปรเจกต์ที่ยอมให้ burst ได้ 2
        #  เพราะที่นั่นเป้าหมายคือไม่ทิ้งเฟรมที่มาเป็นช่อ ส่วนที่นี่คือคุมภาระ CPU)
        self._tokens = 1.0
        self._last_refill = time.monotonic()

        # นับว่าแต่ละกล้องได้คิวไปกี่ครั้ง ใช้ยืนยันว่าแบ่งกันยุติธรรมจริง
        self._served: dict[str, int] = {}

        # จำนวนครั้งที่ต้องให้รอเพราะเพดานรวมเต็ม = สัญญาณว่าตั้ง DETECT_FPS สูงเกินเครื่อง
        self._throttled = 0

    # ------------------------------------------------------------------
    # การขอคิว
    # ------------------------------------------------------------------
    def slot(self, camera_id: str) -> "_DetectSlot":
        """ขอคิวตรวจจับหนึ่งครั้งสำหรับกล้องตัวนี้"""
        return _DetectSlot(self, camera_id)

    async def _acquire(self, camera_id: str) -> None:
        await self._gate.acquire()

        # เข้าประตูมาแล้วค่อยรอ token ของเพดานรวม
        #
        # ที่รอ "ข้างใน" ประตูโดยตั้งใจ: การรอตรงนี้คือการหน่วงทั้งระบบ
        # ซึ่งเป็นสิ่งที่ต้องการ และยังรักษาลำดับ FIFO ของคิวไว้ครบ
        # ถ้าไปรอข้างนอกประตู ลำดับคิวจะสลับกันตามจังหวะที่ token ครบ
        try:
            wait_for = self._refill_and_take()
            if wait_for > 0:
                self._throttled += 1
                await asyncio.sleep(wait_for)
                # หลังหลับครบเวลาแล้ว token ต้องพอแน่นอน เพราะไม่มีใครมาแย่งได้
                # (เรายังถือประตูอยู่ คนอื่นเข้ามาหยิบ token ไม่ได้)
                self._refill_and_take()
        except BaseException:
            # รอไม่สำเร็จ (เช่นถูก cancel ตอนปิดระบบ) ต้องคืนประตูก่อนโยนต่อ
            # ไม่งั้นกล้องตัวอื่นจะค้างรอประตูที่ไม่มีใครปล่อยตลอดไป
            self._gate.release()
            raise

        self._served[camera_id] = self._served.get(camera_id, 0) + 1

    def _release(self) -> None:
        # เรียกจาก __aexit__ เท่านั้น ซึ่งแปลว่าเราถือประตูอยู่แน่นอน
        self._gate.release()

    def _refill_and_take(self) -> float:
        """เติม token ตามเวลาที่ผ่านไป แล้วหยิบหนึ่งใบถ้ามีพอ

        คืนค่า 0.0 ถ้าหยิบได้แล้ว หรือจำนวนวินาทีที่ต้องรอถ้ายังไม่พอ
        """
        now = time.monotonic()
        self._tokens = min(1.0, self._tokens + (now - self._last_refill) * self.total_fps)
        self._last_refill = now

        if self._tokens >= 1.0:
            self._tokens -= 1.0
            return 0.0

        return (1.0 - self._tokens) / self.total_fps

    # ------------------------------------------------------------------
    # สถานะ
    # ------------------------------------------------------------------
    def status(self) -> dict:
        """ข้อมูลสำหรับ /api/health - ดูได้ว่าแบ่งคิวกันยุติธรรมไหม"""
        return {
            "total_fps_cap": self.total_fps,
            "served": dict(self._served),
            "throttled": self._throttled,
        }


class _DetectSlot:
    """ตัวช่วยให้เขียน async with ได้ (ไม่ต้องใช้เองจากข้างนอก)"""

    __slots__ = ("_scheduler", "_camera_id")

    def __init__(self, scheduler: DetectScheduler, camera_id: str) -> None:
        self._scheduler = scheduler
        self._camera_id = camera_id

    async def __aenter__(self) -> None:
        await self._scheduler._acquire(self._camera_id)

    async def __aexit__(self, exc_type, exc, tb) -> None:
        self._scheduler._release()
